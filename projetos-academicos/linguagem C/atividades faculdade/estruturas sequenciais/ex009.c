/*Escreva uma função chamada imprimeAPC que deverá imprimir uma palavra usando caracteres ASCII. 
Resultado
    _    ____   ____ 
   / \  |  _ \ / ___|
  / _ \ | |_) | |    
 / ___ \|  __/| |___ 
/_/   \_\_|    \____|
*/
#include <stdio.h>
void imprimeAPC(){
    printf("    _    ____   ____ \n");
    printf("   / \\  |  _ \\ / ___|\n");
    printf("  / _ \\ | |_) | |    \n");
    printf(" / ___ \\|  __/| |___ \n");
    printf("/_/   \\_\\_|    \\____|\n");
}
int main(){
    imprimeAPC();
    return 0;
}